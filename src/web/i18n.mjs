export function translate(locale, key, values = {}) {
  const dictionary = Object.hasOwn(messages, locale) ? messages[locale] : messages.ko;
  const template = Object.hasOwn(dictionary, key) ? dictionary[key] : Object.hasOwn(messages.ko, key) ? messages.ko[key] : String(key ?? '');
  return template.replace(/\{(\w+)\}/g, (match, name) => Object.hasOwn(values, name) ? String(values[name]) : match);
}
